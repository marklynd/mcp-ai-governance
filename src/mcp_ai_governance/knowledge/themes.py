THEMES: Final[Mapping[str, Theme]] = {theme.id: theme for theme in _THEME_LIST}

ALL_THEME_IDS: Final[frozenset[str]] = frozenset(THEMES)


def get_theme(theme_id: str) -> Theme:
    """Return the theme with ``theme_id``.

    Raises:
        KeyError: If the theme is not part of the controlled vocabulary.
    """
    return THEMES[theme_id]
