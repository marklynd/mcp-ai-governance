"""Controlled vocabulary of AI governance themes.

The mapping engine does not use an LLM. It resolves a free-text control
description to a small set of *themes* (this module), then to the framework
controls tagged with those themes (see the per-framework modules). Keeping the
theme layer separate means a new framework only has to tag its controls with
existing themes to become mappable, and it keeps the keyword lists in one
reviewable place.

Signal phrases are matched against normalised text (see ``mcp_ai_governance.text``).
Multi-word phrases score higher than single words because they are far less
ambiguous.
"""

